import { expect, test } from "@playwright/test";
import path from "node:path";
import { db } from "./helpers";
import { opticalSignature } from "../../src/lib/optical-compatibility";

test("décision professionnelle synthétique : attente, incompatible, puis validation", async ({ page, browser }) => {
  const product = await db.product.findUniqueOrThrow({ where: { slug: "titane-minimaliste-noir-mat" }, include: { variants: { orderBy: { sortOrder: "asc" } } } });
  const lens = await db.lensType.findFirstOrThrow({ where: { kind: "SINGLE_VISION", isActive: true } });
  const index = await db.lensIndex.findFirstOrThrow({ where: { value: "1.60" } });
  const treatments = await db.lensTreatment.findMany({ where: { isDefault: true } });
  expect(treatments).toHaveLength(1);
  const combination = { productId: product.id, variantId: product.variants[0]!.id, lensTypeId: lens.id, lensIndexId: index.id, treatmentIds: [treatments[0]!.id] };
  const signature = opticalSignature(combination);
  const original = await db.opticalCompatibilityRule.findUniqueOrThrow({ where: { signature } });
  const owner = await browser.newContext({ storageState: path.join(import.meta.dirname, ".auth", "admin.json"), baseURL: test.info().project.use.baseURL });
  const admin = await owner.newPage();
  try {
    await admin.goto("/admin/verres/compatibilite");
    const form = admin.locator("form");
    await form.locator('[name="productId"]').selectOption(product.id);
    await form.locator('[name="variantId"]').selectOption(combination.variantId);
    await form.locator('[name="lensTypeId"]').selectOption(lens.id);
    await form.locator('[name="lensIndexId"]').selectOption(index.id);
    await form.locator(`input[name="treatmentIds"][value="${treatments[0]!.id}"]`).check();
    await form.locator('[name="status"]').selectOption("INCOMPATIBLE");
    await form.getByRole("button", { name: "Enregistrer" }).click();
    await expect(form.getByRole("alert")).toContainText("nom du professionnel");
    expect((await db.opticalCompatibilityRule.findUniqueOrThrow({ where: { signature } })).status).toBe("APPROVED");
    await form.locator('[name="productId"]').selectOption(product.id);
    await form.locator('[name="variantId"]').selectOption(combination.variantId);
    await form.locator('[name="lensTypeId"]').selectOption(lens.id);
    await form.locator('[name="lensIndexId"]').selectOption(index.id);
    await form.locator(`input[name="treatmentIds"][value="${treatments[0]!.id}"]`).check();
    await form.locator('[name="status"]').selectOption("INCOMPATIBLE");
    await form.locator('[name="reviewer"]').fill("TEST ONLY — NOT A PROFESSIONAL APPROVAL");
    await form.locator('[name="reviewDate"]').fill("2026-01-01");
    await form.locator('[name="evidence"]').fill("Test-only fixture; no clinical or business decision.");
    await form.locator('[name="confirmed"]').check();
    await form.getByRole("button", { name: "Enregistrer" }).click();
    await expect(form.getByRole("status")).toContainText("Décision enregistrée");
    expect((await db.opticalCompatibilityRule.findUniqueOrThrow({ where: { signature } })).status).toBe("INCOMPATIBLE");
    await page.goto(`/configurateur/${product.slug}`);
    await page.getByRole("button", { name: "Verres & traitements", exact: true }).click();
    await page.locator(`input[name="lensTypeId"][value="${lens.id}"]`).check({ force: true });
    await page.locator(`input[name="lensIndexId"][value="${index.id}"]`).check({ force: true });
    await expect(page.getByRole("status")).toContainText("incompatible");
    await page.getByRole("button", { name: /^Ordonnance/ }).click();
    await page.getByRole("button", { name: /Saisir les mesures/ }).click();
    await page.locator("#rightSphere").fill("-2");
    await page.locator("#leftSphere").fill("-2");
    await page.getByRole("button", { name: /^Récapitulatif/ }).click();
    await expect(page.getByRole("status")).toContainText("incompatible");
    await page.getByRole("button", { name: /Ajouter au panier/ }).click();
    await expect(page.getByText(/combinaison de monture et de verres n'est pas disponible/)).toBeVisible();
    await form.locator('[name="productId"]').selectOption(product.id);
    await form.locator('[name="variantId"]').selectOption(combination.variantId);
    await form.locator('[name="lensTypeId"]').selectOption(lens.id);
    await form.locator('[name="lensIndexId"]').selectOption(index.id);
    await form.locator(`input[name="treatmentIds"][value="${treatments[0]!.id}"]`).check();
    await form.locator('[name="status"]').selectOption("PENDING_REVIEW");
    await form.getByRole("button", { name: "Enregistrer" }).click();
    await expect.poll(async () => (await db.opticalCompatibilityRule.findUniqueOrThrow({ where: { signature } })).status).toBe("PENDING_REVIEW");
    await page.reload();
    await page.getByRole("button", { name: "Verres & traitements", exact: true }).click();
    await page.locator(`input[name="lensTypeId"][value="${lens.id}"]`).check({ force: true });
    await page.locator(`input[name="lensIndexId"][value="${index.id}"]`).check({ force: true });
    await expect(page.getByRole("status")).toContainText("en attente");
    await form.locator('[name="productId"]').selectOption(product.id);
    await form.locator('[name="variantId"]').selectOption(combination.variantId);
    await form.locator('[name="lensTypeId"]').selectOption(lens.id);
    await form.locator('[name="lensIndexId"]').selectOption(index.id);
    await form.locator(`input[name="treatmentIds"][value="${treatments[0]!.id}"]`).check();
    await form.locator('[name="status"]').selectOption("APPROVED");
    await form.locator('[name="reviewer"]').fill("TEST ONLY — NOT A PROFESSIONAL APPROVAL");
    await form.locator('[name="reviewDate"]').fill("2026-01-01");
    await form.locator('[name="evidence"]').fill("Test-only fixture; no clinical or business decision.");
    await form.locator('[name="confirmed"]').check();
    await form.getByRole("button", { name: "Enregistrer" }).click();
    await expect.poll(async () => (await db.opticalCompatibilityRule.findUniqueOrThrow({ where: { signature } })).status).toBe("APPROVED");
    await page.reload();
    await page.getByRole("button", { name: "Verres & traitements", exact: true }).click();
    await page.locator(`input[name="lensTypeId"][value="${lens.id}"]`).check({ force: true });
    await page.locator(`input[name="lensIndexId"][value="${index.id}"]`).check({ force: true });
    await expect(page.getByRole("status")).toContainText("enregistrée comme validée");
    const queueStatus = admin.locator("#optical-rule-status");
    await queueStatus.selectOption("APPROVED");
    await admin.getByRole("button", { name: "Filtrer" }).click();
    await expect(admin.getByRole("heading", { name: /Décisions enregistrées/ })).toBeVisible();
    await expect(admin.locator("div.space-y-3 > div").filter({ hasText: product.name }).first()).toBeVisible();
    expect(await db.auditLog.count({ where: { entityType: "OpticalCompatibilityRule", entityId: original.id } })).toBeGreaterThanOrEqual(3);
  } finally {
    await db.opticalCompatibilityRule.update({ where: { signature }, data: { status: original.status, reviewer: original.reviewer, reviewedAt: original.reviewedAt, evidence: original.evidence, actorEmail: original.actorEmail } });
    await owner.close();
  }
});
